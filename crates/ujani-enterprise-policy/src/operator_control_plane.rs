//! Tenant-scoped operator control-plane application service.
//!
//! This module authenticates short-lived operator sessions and authorizes
//! tenant-scoped, read-only fleet overview requests. It deliberately contains
//! no HTTP listener, identity-provider integration, device telemetry collector,
//! or production repository implementation. The hosting adapter must validate
//! the upstream identity-provider response before minting a session, provide a
//! durable tenant-isolated repository and append-only audit sink, and expose
//! this service only behind HTTPS with secure session cookies and CSRF controls.
use hmac::{Hmac, KeyInit, Mac};
use sha2::Sha256;
use std::collections::{HashMap, HashSet};
use std::fmt::Write as FmtWrite;
use std::sync::Arc;
use zeroize::Zeroize;

type HmacSha256 = Hmac<Sha256>;
const SESSION_DOMAIN: &[u8] = b"UJANI-ENTERPRISE-OPERATOR-SESSION-V1\0";
pub const OPERATOR_SESSION_MAX_TTL_MS: u64 = 15 * 60 * 1000;
const SESSION_KEYRING_DOMAIN: &[u8] = b"UJANI-ENTERPRISE-OPERATOR-SESSION-KEYRING-V1\0";
const CLOCK_SKEW_TOLERANCE_MS: u64 = 30_000;
const MAX_OVERVIEW_AGE_MS: u64 = 60_000;
const MAX_MODEL_MEMORY_ESTIMATE_MB: u64 = 16_777_216;
const MAX_DEVICES: usize = 10_000;
const MAX_WORKLOADS: usize = 1_000;
const MAX_APPROVALS: usize = 1_000;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OperatorRole {
    Viewer,
    Operator,
    Administrator,
}
impl OperatorRole {
    fn as_byte(self) -> u8 {
        match self {
            Self::Viewer => 1,
            Self::Operator => 2,
            Self::Administrator => 3,
        }
    }
    fn from_byte(value: u8) -> Option<Self> {
        match value {
            1 => Some(Self::Viewer),
            2 => Some(Self::Operator),
            3 => Some(Self::Administrator),
            _ => None,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OperatorSessionClaims {
    pub subject_id: String,
    pub tenant_id: String,
    pub role: OperatorRole,
    pub issued_at_unix_ms: u64,
    pub expires_at_unix_ms: u64,
    /// Must be generated by a cryptographically secure random source in the
    /// trusted identity-provider adapter. It is included in the signed token.
    pub nonce: [u8; 16],
}

#[derive(Clone)]
pub struct OperatorSessionAuthenticator {
    key_id: String,
    key: [u8; 32],
}
impl std::fmt::Debug for OperatorSessionAuthenticator {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("OperatorSessionAuthenticator")
            .field("key_id", &self.key_id)
            .field("key", &"[REDACTED]")
            .finish()
    }
}
impl Drop for OperatorSessionAuthenticator {
    fn drop(&mut self) {
        self.key.zeroize();
    }
}
impl OperatorSessionAuthenticator {
    /// Construct from a key supplied by a protected secret provider. Never load
    /// this key from the writable application data directory or a request.
    pub fn new(key_id: impl Into<String>, key: [u8; 32]) -> Result<Self, OperatorAuthError> {
        let key_id = key_id.into();
        if !valid_identifier(&key_id, 128) {
            return Err(OperatorAuthError::InvalidClaims);
        }
        Ok(Self { key_id, key })
    }

    /// Mint only after an external OIDC/SAML adapter has verified issuer,
    /// audience, signature, tenant membership, account status and role mapping.
    /// This method is not an HTTP login endpoint and must never receive
    /// caller-selected tenant or role values directly from a browser.
    pub fn mint_after_identity_verification(
        &self,
        claims: &OperatorSessionClaims,
        now_unix_ms: u64,
    ) -> Result<String, OperatorAuthError> {
        validate_claims(claims, now_unix_ms)?;
        let payload = encode_claims(claims);
        let mut mac =
            HmacSha256::new_from_slice(&self.key).map_err(|_| OperatorAuthError::InvalidKey)?;
        mac.update(SESSION_DOMAIN);
        mac.update(&payload);
        let signature = mac.finalize().into_bytes();
        Ok(format!(
            "{}.{}",
            hex_encode(&payload),
            hex_encode(&signature)
        ))
    }

    pub fn authenticate(
        &self,
        token: &str,
        now_unix_ms: u64,
    ) -> Result<OperatorSessionClaims, OperatorAuthError> {
        if token.len() > 2048 {
            return Err(OperatorAuthError::MalformedToken);
        }
        let (payload_hex, signature_hex) = token
            .split_once('.')
            .ok_or(OperatorAuthError::MalformedToken)?;
        let payload = hex_decode(payload_hex).ok_or(OperatorAuthError::MalformedToken)?;
        let signature = hex_decode(signature_hex).ok_or(OperatorAuthError::MalformedToken)?;
        if signature.len() != 32 {
            return Err(OperatorAuthError::MalformedToken);
        }
        let mut mac =
            HmacSha256::new_from_slice(&self.key).map_err(|_| OperatorAuthError::InvalidKey)?;
        mac.update(SESSION_DOMAIN);
        mac.update(&payload);
        mac.verify_slice(&signature)
            .map_err(|_| OperatorAuthError::InvalidSignature)?;
        let claims = decode_claims(&payload)?;
        validate_claims(&claims, now_unix_ms)?;
        Ok(claims)
    }

    pub fn key_id(&self) -> &str {
        &self.key_id
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OperatorAuthError {
    UnknownKeyId,
    InvalidKey,
    InvalidClaims,
    MalformedToken,
    InvalidSignature,
    Expired,
    FutureIssuedAt,
    InvalidLifetime,
}

fn validate_claims(claims: &OperatorSessionClaims, now: u64) -> Result<(), OperatorAuthError> {
    if !valid_identifier(&claims.subject_id, 128)
        || !valid_identifier(&claims.tenant_id, 128)
        || claims.nonce.iter().all(|byte| *byte == 0)
    {
        return Err(OperatorAuthError::InvalidClaims);
    }
    if claims.issued_at_unix_ms > now.saturating_add(CLOCK_SKEW_TOLERANCE_MS) {
        return Err(OperatorAuthError::FutureIssuedAt);
    }
    if claims.expires_at_unix_ms <= claims.issued_at_unix_ms
        || claims
            .expires_at_unix_ms
            .saturating_sub(claims.issued_at_unix_ms)
            > OPERATOR_SESSION_MAX_TTL_MS
    {
        return Err(OperatorAuthError::InvalidLifetime);
    }
    if claims.expires_at_unix_ms <= now {
        return Err(OperatorAuthError::Expired);
    }
    Ok(())
}
fn valid_identifier(value: &str, max: usize) -> bool {
    !value.is_empty()
        && value.len() <= max
        && value
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"._:-".contains(&b))
}
fn encode_claims(claims: &OperatorSessionClaims) -> Vec<u8> {
    let tenant = claims.tenant_id.as_bytes();
    let subject = claims.subject_id.as_bytes();
    let mut out = Vec::with_capacity(38 + tenant.len() + subject.len());
    out.push(1);
    out.push(claims.role.as_byte());
    out.extend_from_slice(&claims.issued_at_unix_ms.to_be_bytes());
    out.extend_from_slice(&claims.expires_at_unix_ms.to_be_bytes());
    out.extend_from_slice(&claims.nonce);
    out.extend_from_slice(&(tenant.len() as u16).to_be_bytes());
    out.extend_from_slice(&(subject.len() as u16).to_be_bytes());
    out.extend_from_slice(tenant);
    out.extend_from_slice(subject);
    out
}
fn decode_claims(bytes: &[u8]) -> Result<OperatorSessionClaims, OperatorAuthError> {
    if bytes.len() < 38 || bytes[0] != 1 {
        return Err(OperatorAuthError::MalformedToken);
    }
    let role = OperatorRole::from_byte(bytes[1]).ok_or(OperatorAuthError::MalformedToken)?;
    let issued_at_unix_ms = u64::from_be_bytes(
        bytes[2..10]
            .try_into()
            .map_err(|_| OperatorAuthError::MalformedToken)?,
    );
    let expires_at_unix_ms = u64::from_be_bytes(
        bytes[10..18]
            .try_into()
            .map_err(|_| OperatorAuthError::MalformedToken)?,
    );
    let nonce: [u8; 16] = bytes[18..34]
        .try_into()
        .map_err(|_| OperatorAuthError::MalformedToken)?;
    let tenant_len = u16::from_be_bytes(
        bytes[34..36]
            .try_into()
            .map_err(|_| OperatorAuthError::MalformedToken)?,
    ) as usize;
    let subject_len = u16::from_be_bytes(
        bytes[36..38]
            .try_into()
            .map_err(|_| OperatorAuthError::MalformedToken)?,
    ) as usize;
    if tenant_len == 0
        || subject_len == 0
        || 38usize
            .checked_add(tenant_len)
            .and_then(|v| v.checked_add(subject_len))
            != Some(bytes.len())
    {
        return Err(OperatorAuthError::MalformedToken);
    }
    let tenant_id = std::str::from_utf8(&bytes[38..38 + tenant_len])
        .map_err(|_| OperatorAuthError::MalformedToken)?
        .to_owned();
    let subject_id = std::str::from_utf8(&bytes[38 + tenant_len..])
        .map_err(|_| OperatorAuthError::MalformedToken)?
        .to_owned();
    Ok(OperatorSessionClaims {
        subject_id,
        tenant_id,
        role,
        issued_at_unix_ms,
        expires_at_unix_ms,
        nonce,
    })
}
fn hex_encode(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push(HEX[(byte >> 4) as usize] as char);
        out.push(HEX[(byte & 0x0f) as usize] as char);
    }
    out
}
fn hex_decode(value: &str) -> Option<Vec<u8>> {
    if value.is_empty() || value.len() & 1 == 1 {
        return None;
    }
    let mut out = Vec::with_capacity(value.len() / 2);
    for pair in value.as_bytes().chunks(2) {
        let digit = |b: u8| match b {
            b'0'..=b'9' => Some(b - b'0'),
            b'a'..=b'f' => Some(b - b'a' + 10),
            b'A'..=b'F' => Some(b - b'A' + 10),
            _ => None,
        };
        out.push((digit(pair[0])? << 4) | digit(pair[1])?);
    }
    Some(out)
}

/// Versioned operator-session signer/verifier with bounded, explicitly configured
/// key overlap. The active key signs new sessions; previous keys verify only while
/// they remain in the configured key set. Removing a key revokes all sessions
/// minted with it. Key material must come from a protected customer-managed provider.
pub struct OperatorSessionKeyRing {
    active_key_id: String,
    keys: HashMap<String, [u8; 32]>,
}
impl std::fmt::Debug for OperatorSessionKeyRing {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("OperatorSessionKeyRing")
            .field("active_key_id", &self.active_key_id)
            .field("configured_key_ids", &self.keys.keys().collect::<Vec<_>>())
            .field("key_material", &"[REDACTED]")
            .finish()
    }
}
impl Drop for OperatorSessionKeyRing {
    fn drop(&mut self) {
        for key in self.keys.values_mut() {
            key.zeroize();
        }
    }
}

/// Customer-owned signing boundary for operator sessions. A hardware-backed
/// provider can implement this without exporting HMAC key material to UJANI.
pub trait OperatorSessionMacProvider: Send + Sync {
    /// Sign with the active key and return its public, non-secret key identifier.
    fn sign_active(&self, payload: &[u8]) -> Result<(String, Vec<u8>), OperatorAuthError>;

    /// Verify with the identified active/overlap key; revoked or unknown IDs fail closed.
    fn verify(
        &self,
        key_id: &str,
        payload: &[u8],
        signature: &[u8],
    ) -> Result<(), OperatorAuthError>;
}

fn operator_session_mac_input(key_id: &str, payload: &[u8]) -> Vec<u8> {
    let mut input =
        Vec::with_capacity(SESSION_KEYRING_DOMAIN.len() + key_id.len() + 1 + payload.len());
    input.extend_from_slice(SESSION_KEYRING_DOMAIN);
    input.extend_from_slice(key_id.as_bytes());
    input.push(0);
    input.extend_from_slice(payload);
    input
}

/// Session verifier adapter for customer-selected HSM/KMS/OS key providers.
pub struct OperatorSessionProviderVerifier<P> {
    provider: P,
}
impl<P> OperatorSessionProviderVerifier<P> {
    pub fn new(provider: P) -> Self {
        Self { provider }
    }
}
impl<P: OperatorSessionMacProvider> OperatorSessionProviderVerifier<P> {
    pub fn mint_after_identity_verification(
        &self,
        claims: &OperatorSessionClaims,
        now_unix_ms: u64,
    ) -> Result<String, OperatorAuthError> {
        validate_claims(claims, now_unix_ms)?;
        let payload = encode_claims(claims);
        let (key_id, signature) = self.provider.sign_active(&payload)?;
        if !valid_identifier(&key_id, 128) || key_id.contains('.') || signature.len() != 32 {
            return Err(OperatorAuthError::InvalidClaims);
        }
        Ok(format!(
            "{}.{}.{}",
            key_id,
            hex_encode(&payload),
            hex_encode(&signature)
        ))
    }

    pub fn authenticate(
        &self,
        token: &str,
        now_unix_ms: u64,
    ) -> Result<OperatorSessionClaims, OperatorAuthError> {
        if token.len() > 2300 {
            return Err(OperatorAuthError::MalformedToken);
        }
        let mut parts = token.split('.');
        let key_id = parts.next().ok_or(OperatorAuthError::MalformedToken)?;
        let payload_hex = parts.next().ok_or(OperatorAuthError::MalformedToken)?;
        let signature_hex = parts.next().ok_or(OperatorAuthError::MalformedToken)?;
        if parts.next().is_some() || !valid_identifier(key_id, 128) || key_id.contains('.') {
            return Err(OperatorAuthError::MalformedToken);
        }
        let payload = hex_decode(payload_hex).ok_or(OperatorAuthError::MalformedToken)?;
        let signature = hex_decode(signature_hex).ok_or(OperatorAuthError::MalformedToken)?;
        if signature.len() != 32 {
            return Err(OperatorAuthError::MalformedToken);
        }
        self.provider.verify(key_id, &payload, &signature)?;
        let claims = decode_claims(&payload)?;
        validate_claims(&claims, now_unix_ms)?;
        Ok(claims)
    }
}

impl OperatorSessionKeyRing {
    /// The key set may contain the active key and a small number of previous keys
    /// during a planned rotation overlap. Duplicate and invalid IDs are rejected.
    pub fn new(
        active_key_id: impl Into<String>,
        keys: Vec<(String, [u8; 32])>,
    ) -> Result<Self, OperatorAuthError> {
        let active_key_id = active_key_id.into();
        let invalid_configuration = !valid_identifier(&active_key_id, 128)
            || active_key_id.contains('.')
            || keys.is_empty()
            || keys.len() > 4;
        let mut invalid_key_set = invalid_configuration;
        let mut indexed: HashMap<String, [u8; 32]> = HashMap::with_capacity(keys.len());
        for (key_id, mut key) in keys {
            if invalid_key_set
                || !valid_identifier(&key_id, 128)
                || key_id.contains('.')
                || indexed.contains_key(&key_id)
            {
                key.zeroize();
                invalid_key_set = true;
                continue;
            }
            indexed.insert(key_id, key);
        }
        if invalid_key_set {
            for existing in indexed.values_mut() {
                existing.zeroize();
            }
            return Err(OperatorAuthError::InvalidClaims);
        }
        if !indexed.contains_key(&active_key_id) {
            for existing in indexed.values_mut() {
                existing.zeroize();
            }
            return Err(OperatorAuthError::UnknownKeyId);
        }
        Ok(Self {
            active_key_id,
            keys: indexed,
        })
    }

    pub fn active_key_id(&self) -> &str {
        &self.active_key_id
    }

    /// Mint a key-ring token. The key ID is authenticated as part of the
    /// domain-separated MAC input; it is not an authorization claim.
    pub fn mint_after_identity_verification(
        &self,
        claims: &OperatorSessionClaims,
        now_unix_ms: u64,
    ) -> Result<String, OperatorAuthError> {
        validate_claims(claims, now_unix_ms)?;
        let key = self
            .keys
            .get(&self.active_key_id)
            .ok_or(OperatorAuthError::UnknownKeyId)?;
        let payload = encode_claims(claims);
        let mut mac = HmacSha256::new_from_slice(key).map_err(|_| OperatorAuthError::InvalidKey)?;
        mac.update(SESSION_KEYRING_DOMAIN);
        mac.update(self.active_key_id.as_bytes());
        mac.update(&[0]);
        mac.update(&payload);
        let signature = mac.finalize().into_bytes();
        Ok(format!(
            "{}.{}.{}",
            self.active_key_id,
            hex_encode(&payload),
            hex_encode(&signature)
        ))
    }

    /// Verify only keys explicitly present in the configured key set. Removing
    /// a retired/revoked key immediately invalidates tokens signed by that key.
    pub fn authenticate(
        &self,
        token: &str,
        now_unix_ms: u64,
    ) -> Result<OperatorSessionClaims, OperatorAuthError> {
        if token.len() > 2300 {
            return Err(OperatorAuthError::MalformedToken);
        }
        let mut parts = token.split('.');
        let key_id = parts.next().ok_or(OperatorAuthError::MalformedToken)?;
        let payload_hex = parts.next().ok_or(OperatorAuthError::MalformedToken)?;
        let signature_hex = parts.next().ok_or(OperatorAuthError::MalformedToken)?;
        if parts.next().is_some() || !valid_identifier(key_id, 128) || key_id.contains('.') {
            return Err(OperatorAuthError::MalformedToken);
        }
        let key = self
            .keys
            .get(key_id)
            .ok_or(OperatorAuthError::UnknownKeyId)?;
        let payload = hex_decode(payload_hex).ok_or(OperatorAuthError::MalformedToken)?;
        let signature = hex_decode(signature_hex).ok_or(OperatorAuthError::MalformedToken)?;
        if signature.len() != 32 {
            return Err(OperatorAuthError::MalformedToken);
        }
        let mut mac = HmacSha256::new_from_slice(key).map_err(|_| OperatorAuthError::InvalidKey)?;
        mac.update(SESSION_KEYRING_DOMAIN);
        mac.update(key_id.as_bytes());
        mac.update(&[0]);
        mac.update(&payload);
        mac.verify_slice(&signature)
            .map_err(|_| OperatorAuthError::InvalidSignature)?;
        let claims = decode_claims(&payload)?;
        validate_claims(&claims, now_unix_ms)?;
        Ok(claims)
    }
}

