pub struct OperatorControlPlane<V, R, A> {
    authenticator: V,
    repository: Arc<R>,
    audit: Arc<A>,
}
impl<V, R, A> OperatorControlPlane<V, R, A>
where
    V: OperatorSessionVerifier,
    R: OperatorOverviewRepository,
    A: OperatorAuditSink,
{
    pub fn new(authenticator: V, repository: Arc<R>, audit: Arc<A>) -> Self {
        Self {
            authenticator,
            repository,
            audit,
        }
    }

    /// Authorize a short-lived session, read only that tenant's overview, validate
    /// the response contract, and durably audit the access before returning it.
    pub fn get_overview(
        &self,
        session_token: &str,
        now_unix_ms: u64,
    ) -> Result<OperatorOverview, OperatorServiceError> {
        let claims = self
            .authenticator
            .verify_session(session_token, now_unix_ms)
            .map_err(|_| OperatorServiceError::Unauthorized)?;
        let overview = match self
            .repository
            .load_tenant_overview(&claims.tenant_id, now_unix_ms)
        {
            Ok(value) => value,
            Err(_) => {
                self.audit
                    .append(&OperatorAuditEvent {
                        tenant_id: claims.tenant_id,
                        subject_id: claims.subject_id,
                        role: claims.role,
                        occurred_at_unix_ms: now_unix_ms,
                        outcome: OperatorAuditOutcome::RepositoryDenied,
                    })
                    .map_err(|_| OperatorServiceError::AuditUnavailable)?;
                return Err(OperatorServiceError::RepositoryUnavailable);
            }
        };
        let outcome = if overview.tenant_id != claims.tenant_id
            || validate_overview(&overview, now_unix_ms).is_err()
        {
            OperatorAuditOutcome::InvalidOverview
        } else {
            OperatorAuditOutcome::ReadSucceeded
        };
        self.audit
            .append(&OperatorAuditEvent {
                tenant_id: claims.tenant_id.clone(),
                subject_id: claims.subject_id,
                role: claims.role,
                occurred_at_unix_ms: now_unix_ms,
                outcome,
            })
            .map_err(|_| OperatorServiceError::AuditUnavailable)?;
        match outcome {
            OperatorAuditOutcome::ReadSucceeded => Ok(overview),
            OperatorAuditOutcome::InvalidOverview if overview.tenant_id != claims.tenant_id => {
                Err(OperatorServiceError::InvalidTenantBoundary)
            }
            OperatorAuditOutcome::InvalidOverview => Err(OperatorServiceError::InvalidOverview),
            OperatorAuditOutcome::RepositoryDenied => {
                Err(OperatorServiceError::RepositoryUnavailable)
            }
        }
    }
}
fn validate_overview(overview: &OperatorOverview, now: u64) -> Result<(), ()> {
    if overview.schema_version != 1
        || !valid_identifier(&overview.tenant_id, 128)
        || overview.generated_at_unix_ms == 0
        || overview.generated_at_unix_ms > now.saturating_add(CLOCK_SKEW_TOLERANCE_MS)
        || now.saturating_sub(overview.generated_at_unix_ms) > MAX_OVERVIEW_AGE_MS
        || overview.devices.len() > MAX_DEVICES
        || overview.workloads.len() > MAX_WORKLOADS
        || overview.approvals.len() > MAX_APPROVALS
        || overview.model_inventory.len() > MAX_DEVICES
    {
        return Err(());
    }
    let fleet = &overview.fleet;
    if fleet.registered_devices != overview.devices.len()
        || fleet.trusted_consented_devices > fleet.registered_devices
        || fleet.online_fresh_devices > fleet.trusted_consented_devices
        || fleet.schedulable_devices > fleet.online_fresh_devices
    {
        return Err(());
    }
    let mut ids = HashSet::with_capacity(overview.devices.len());
    for device in &overview.devices {
        if !valid_identifier(&device.device_id, 128)
            || device.display_name.len() > 256
            || device.platform.is_empty()
            || device.platform.len() > 64
            || device.trust_state.is_empty()
            || device.trust_state.len() > 64
            || device.availability.is_empty()
            || device.availability.len() > 64
            || !ids.insert(device.device_id.as_str())
            || device.remaining_cpu_millis == Some(0)
            || device.remaining_memory_mb == Some(0)
        {
            return Err(());
        }
    }

    let mut inventory_devices = HashSet::with_capacity(overview.model_inventory.len());
    for inventory in &overview.model_inventory {
        if !valid_identifier(&inventory.device_id, 128)
            || !ids.contains(inventory.device_id.as_str())
            || !inventory_devices.insert(inventory.device_id.as_str())
            || inventory.schema_version != 1
            || inventory.generated_at_unix_ms == 0
            || !valid_bounded_text(&inventory.platform.os, 32)
            || inventory
                .platform
                .os_version
                .as_ref()
                .is_some_and(|value| !valid_bounded_text(value, 64))
            || !valid_bounded_text(&inventory.platform.architecture, 32)
            || inventory
                .hardware
                .cpu_logical_cores
                .is_some_and(|value| value == 0 || value > 65_535)
            || inventory
                .hardware
                .memory_total_mb
                .is_some_and(|value| value == 0 || value > 16_777_216)
            || inventory
                .hardware
                .memory_total_mb
                .zip(inventory.hardware.memory_available_mb)
                .is_some_and(|(total, available)| available > total)
            || inventory.hardware.accelerators.len() > 32
            || inventory.privacy.as_ref().is_some_and(|privacy| {
                privacy.contains_prompts
                    || privacy.contains_user_files
                    || privacy.contains_local_paths
                    || privacy.contains_credentials
            })
            || inventory.generated_at_unix_ms > now.saturating_add(CLOCK_SKEW_TOLERANCE_MS)
            || now.saturating_sub(inventory.generated_at_unix_ms) > MAX_OVERVIEW_AGE_MS
            || inventory
                .hardware
                .memory_available_mb
                .is_some_and(|value| value > 16_777_216)
            || inventory.runtimes.len() > 16
            || inventory.models.len() > 512
        {
            return Err(());
        }
        for accelerator in &inventory.hardware.accelerators {
            if !["gpu", "npu", "other"].contains(&accelerator.kind.as_str())
                || accelerator
                    .vendor
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 64))
                || accelerator
                    .device_family
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 96))
                || accelerator
                    .runtime_api
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 64))
                || !valid_inventory_evidence(&accelerator.evidence, now)
            {
                return Err(());
            }
        }
        let mut runtime_ids = HashSet::with_capacity(inventory.runtimes.len());
        for runtime in &inventory.runtimes {
            if !valid_identifier(&runtime.runtime_id, 96)
                || !valid_bounded_text(&runtime.provider, 64)
                || runtime
                    .version
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 64))
                || !["available", "unavailable", "unknown"].contains(&runtime.availability.as_str())
                || ![
                    "loopback_only",
                    "local_socket",
                    "enterprise_internal",
                    "not_applicable",
                    "unknown",
                ]
                .contains(&runtime.network_scope.as_str())
                || !runtime_ids.insert(runtime.runtime_id.as_str())
                || !valid_inventory_evidence(&runtime.evidence, now)
            {
                return Err(());
            }
        }
        let mut model_ids = HashSet::with_capacity(inventory.models.len());
        for model in &inventory.models {
            if !valid_bounded_text(&model.model_ref, 160)
                || !valid_identifier(&model.runtime_id, 96)
                || !valid_bounded_text(&model.display_name, 160)
                || model
                    .family
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 96))
                || model
                    .version
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 64))
                || !["installed", "downloadable", "unavailable", "unknown"]
                    .contains(&model.availability.as_str())
                || model.context_length_tokens == Some(0)
                || model
                    .estimated_min_memory_mb
                    .is_some_and(|value| value == 0 || value > MAX_MODEL_MEMORY_ESTIMATE_MB)
                || model.capabilities.len() > 16
                || model.capabilities.iter().collect::<HashSet<_>>().len()
                    != model.capabilities.len()
                || model.capabilities.iter().any(|value| {
                    ![
                        "chat",
                        "reasoning",
                        "coding",
                        "vision",
                        "embeddings",
                        "tool_use",
                        "streaming",
                        "audio_input",
                        "audio_output",
                        "unknown",
                    ]
                    .contains(&value.as_str())
                })
                || !model_ids.insert(model.model_ref.as_str())
                || !runtime_ids.contains(model.runtime_id.as_str())
                || !valid_inventory_evidence(&model.evidence, now)
            {
                return Err(());
            }
        }
    }

    for workload in &overview.workloads {
        if !valid_identifier(&workload.workload_id, 128)
            || workload.title.len() > 256
            || workload.state.len() > 64
            || workload.class.len() > 64
            || workload.reason.as_ref().is_some_and(|v| v.len() > 512)
        {
            return Err(());
        }
    }
    for approval in &overview.approvals {
        if !valid_identifier(&approval.approval_id, 128)
            || approval.title.len() > 256
            || approval.state.len() > 64
            || approval.requester.len() > 128
            || approval.scope.len() > 256
            || approval.expires_at.as_ref().is_some_and(|v| v.len() > 64)
        {
            return Err(());
        }
    }
    Ok(())
}

