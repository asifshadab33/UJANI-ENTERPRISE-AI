impl OperatorOverview {
    /// Serialize the validated overview using the exact version-1 console field names.
    /// Call only after `OperatorControlPlane::get_overview` has authorized and audited it.
    pub fn to_json(&self) -> String {
        let mut out = String::with_capacity(1024 + self.devices.len() * 256);
        let _ = write!(
            &mut out,
            "{{\"schema_version\":{},\"generated_at_unix_ms\":{},\"fleet\":{{\"registered_devices\":{},\"trusted_consented_devices\":{},\"online_fresh_devices\":{},\"schedulable_devices\":{}}},\"devices\":[",
            self.schema_version, self.generated_at_unix_ms,
            self.fleet.registered_devices, self.fleet.trusted_consented_devices,
            self.fleet.online_fresh_devices, self.fleet.schedulable_devices
        );
        for (index, device) in self.devices.iter().enumerate() {
            if index > 0 {
                out.push(',');
            }
            let _ = write!(
                &mut out,
                "{{\"device_id\":{},\"display_name\":{},\"platform\":{},\"trust_state\":{},\"availability\":{},\"remaining_cpu_millis\":{},\"remaining_memory_mb\":{},\"last_seen_unix_ms\":{}}}",
                json_string(&device.device_id), json_string(&device.display_name),
                json_string(&device.platform), json_string(&device.trust_state),
                json_string(&device.availability),
                json_optional_number(device.remaining_cpu_millis),
                json_optional_number(device.remaining_memory_mb), device.last_seen_unix_ms
            );
        }
        out.push_str("],\"workloads\":[");
        for (index, workload) in self.workloads.iter().enumerate() {
            if index > 0 {
                out.push(',');
            }
            let _ = write!(
                &mut out,
                "{{\"workload_id\":{},\"title\":{},\"state\":{},\"class\":{},\"reason\":{}}}",
                json_string(&workload.workload_id),
                json_string(&workload.title),
                json_string(&workload.state),
                json_string(&workload.class),
                json_optional_string(workload.reason.as_deref())
            );
        }
        out.push_str("],\"approvals\":[");
        for (index, approval) in self.approvals.iter().enumerate() {
            if index > 0 {
                out.push(',');
            }
            let _ = write!(
                &mut out,
                "{{\"approval_id\":{},\"title\":{},\"state\":{},\"requester\":{},\"scope\":{},\"expires_at\":{}}}",
                json_string(&approval.approval_id), json_string(&approval.title),
                json_string(&approval.state), json_string(&approval.requester),
                json_string(&approval.scope), json_optional_string(approval.expires_at.as_deref())
            );
        }
        out.push_str("]}");
        out
    }
}
fn json_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for character in value.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\u{08}' => out.push_str("\\b"),
            '\u{0C}' => out.push_str("\\f"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            value if value <= '\u{1F}' => {
                let _ = write!(&mut out, "\\u{:04x}", value as u32);
            }
            value => out.push(value),
        }
    }
    out.push('"');
    out
}
fn json_optional_string(value: Option<&str>) -> String {
    value.map(json_string).unwrap_or_else(|| "null".into())
}
fn json_optional_number<T: std::fmt::Display>(value: Option<T>) -> String {
    value
        .map(|number| number.to_string())
        .unwrap_or_else(|| "null".into())
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OperatorRepositoryError {
    Unavailable,
}
pub trait OperatorOverviewRepository: Send + Sync {
    /// Implementations MUST filter in the data query itself by this authenticated
    /// tenant. Do not load all tenants and rely on UI-side filtering.
    fn load_tenant_overview(
        &self,
        tenant_id: &str,
        now_unix_ms: u64,
    ) -> Result<OperatorOverview, OperatorRepositoryError>;
}
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OperatorAuditError {
    Unavailable,
}
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OperatorAuditOutcome {
    ReadSucceeded,
    RepositoryDenied,
    InvalidOverview,
}
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OperatorAuditEvent {
    pub tenant_id: String,
    pub subject_id: String,
    pub role: OperatorRole,
    pub occurred_at_unix_ms: u64,
    pub outcome: OperatorAuditOutcome,
}
pub trait OperatorAuditSink: Send + Sync {
    /// Must append durably before returning success. Implementations should
    /// hash-chain or otherwise protect audit records from modification.
    fn append(&self, event: &OperatorAuditEvent) -> Result<(), OperatorAuditError>;
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OperatorServiceError {
    Unauthorized,
    RepositoryUnavailable,
    InvalidTenantBoundary,
    InvalidOverview,
    AuditUnavailable,
}
pub struct OperatorControlPlane<R, A> {
    authenticator: OperatorSessionAuthenticator,
    repository: Arc<R>,
    audit: Arc<A>,
}
impl<R: OperatorOverviewRepository, A: OperatorAuditSink> OperatorControlPlane<R, A> {
    pub fn new(
        authenticator: OperatorSessionAuthenticator,
        repository: Arc<R>,
        audit: Arc<A>,
    ) -> Self {
        Self {
            authenticator,
            repository,
            audit,
        }
    }

    /// Authorize a short-lived session, read only that tenant's overview, validate
    /// the response contract, and durably audit the access before returning it.
    pub fn get_overview(
        &self,
        session_token: &str,
        now_unix_ms: u64,
    ) -> Result<OperatorOverview, OperatorServiceError> {
        let claims = self
            .authenticator
            .authenticate(session_token, now_unix_ms)
            .map_err(|_| OperatorServiceError::Unauthorized)?;
        let overview = match self
            .repository
            .load_tenant_overview(&claims.tenant_id, now_unix_ms)
        {
            Ok(value) => value,
            Err(_) => {
                self.audit
                    .append(&OperatorAuditEvent {
                        tenant_id: claims.tenant_id,
                        subject_id: claims.subject_id,
                        role: claims.role,
                        occurred_at_unix_ms: now_unix_ms,
                        outcome: OperatorAuditOutcome::RepositoryDenied,
                    })
                    .map_err(|_| OperatorServiceError::AuditUnavailable)?;
                return Err(OperatorServiceError::RepositoryUnavailable);
            }
        };
        let outcome = if overview.tenant_id != claims.tenant_id
            || validate_overview(&overview, now_unix_ms).is_err()
        {
            OperatorAuditOutcome::InvalidOverview
        } else {
            OperatorAuditOutcome::ReadSucceeded
        };
        self.audit
            .append(&OperatorAuditEvent {
                tenant_id: claims.tenant_id.clone(),
                subject_id: claims.subject_id,
                role: claims.role,
                occurred_at_unix_ms: now_unix_ms,
                outcome,
            })
            .map_err(|_| OperatorServiceError::AuditUnavailable)?;
        match outcome {
            OperatorAuditOutcome::ReadSucceeded => Ok(overview),
            OperatorAuditOutcome::InvalidOverview if overview.tenant_id != claims.tenant_id => {
                Err(OperatorServiceError::InvalidTenantBoundary)
            }
            OperatorAuditOutcome::InvalidOverview => Err(OperatorServiceError::InvalidOverview),
            OperatorAuditOutcome::RepositoryDenied => {
                Err(OperatorServiceError::RepositoryUnavailable)
            }
        }
    }
}
fn validate_overview(overview: &OperatorOverview, now: u64) -> Result<(), ()> {
    if overview.schema_version != 1
        || !valid_identifier(&overview.tenant_id, 128)
        || overview.generated_at_unix_ms == 0
        || overview.generated_at_unix_ms > now.saturating_add(CLOCK_SKEW_TOLERANCE_MS)
        || now.saturating_sub(overview.generated_at_unix_ms) > MAX_OVERVIEW_AGE_MS
        || overview.devices.len() > MAX_DEVICES
        || overview.workloads.len() > MAX_WORKLOADS
        || overview.approvals.len() > MAX_APPROVALS
    {
        return Err(());
    }
    let fleet = &overview.fleet;
    if fleet.registered_devices != overview.devices.len()
        || fleet.trusted_consented_devices > fleet.registered_devices
        || fleet.online_fresh_devices > fleet.trusted_consented_devices
        || fleet.schedulable_devices > fleet.online_fresh_devices
    {
        return Err(());
    }
    let mut ids = HashSet::with_capacity(overview.devices.len());
    for device in &overview.devices {
        if !valid_identifier(&device.device_id, 128)
            || device.display_name.len() > 256
            || device.platform.is_empty()
            || device.platform.len() > 64
            || device.trust_state.is_empty()
            || device.trust_state.len() > 64
            || device.availability.is_empty()
            || device.availability.len() > 64
            || !ids.insert(device.device_id.as_str())
            || device.remaining_cpu_millis == Some(0)
            || device.remaining_memory_mb == Some(0)
        {
            return Err(());
        }
    }
    for workload in &overview.workloads {
        if !valid_identifier(&workload.workload_id, 128)
            || workload.title.len() > 256
            || workload.state.len() > 64
            || workload.class.len() > 64
            || workload.reason.as_ref().is_some_and(|v| v.len() > 512)
        {
            return Err(());
        }
    }
    for approval in &overview.approvals {
        if !valid_identifier(&approval.approval_id, 128)
            || approval.title.len() > 256
            || approval.state.len() > 64
            || approval.requester.len() > 128
            || approval.scope.len() > 256
            || approval.expires_at.as_ref().is_some_and(|v| v.len() > 64)
        {
            return Err(());
        }
    }
    Ok(())
}

