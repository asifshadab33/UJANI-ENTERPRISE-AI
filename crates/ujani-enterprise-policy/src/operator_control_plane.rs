pub struct OperatorControlPlane<V, R, A> {
    authenticator: V,
    repository: Arc<R>,
    audit: Arc<A>,
}
impl<V, R, A> OperatorControlPlane<V, R, A>
where
    V: OperatorSessionVerifier,
    R: OperatorOverviewRepository,
    A: OperatorAuditSink,
{
    pub fn new(authenticator: V, repository: Arc<R>, audit: Arc<A>) -> Self {
        Self {
            authenticator,
            repository,
            audit,
        }
    }

    /// Authorize a short-lived session, read only that tenant's overview, validate
    /// the response contract, and durably audit the access before returning it.
    /// Authorize a short-lived session, read only that tenant's overview, validate
    /// the response contract, and durably audit the access before returning it.
    /// General operator overview reads remain strict about stale model evidence.
    pub fn get_overview(
        &self,
        session_token: &str,
        now_unix_ms: u64,
    ) -> Result<OperatorOverview, OperatorServiceError> {
        self.get_overview_internal(session_token, now_unix_ms, false)
    }

    /// Model matching may downgrade only age-stale runtime/model evidence to Unknown.
    /// Inventory freshness, tenant identity, device trust, consent-derived scheduling,
    /// malformed/future evidence, and audit requirements remain enforced.
    fn get_overview_for_model_match(
        &self,
        session_token: &str,
        now_unix_ms: u64,
    ) -> Result<OperatorOverview, OperatorServiceError> {
        self.get_overview_internal(session_token, now_unix_ms, true)
    }

    fn get_overview_internal(
        &self,
        session_token: &str,
        now_unix_ms: u64,
        downgrade_stale_model_evidence: bool,
    ) -> Result<OperatorOverview, OperatorServiceError> {
        let claims = self
            .authenticator
            .verify_session(session_token, now_unix_ms)
            .map_err(|_| OperatorServiceError::Unauthorized)?;
        let mut overview = match self
            .repository
            .load_tenant_overview(&claims.tenant_id, now_unix_ms)
        {
            Ok(value) => value,
            Err(_) => {
                self.audit
                    .append(&OperatorAuditEvent {
                        tenant_id: claims.tenant_id,
                        subject_id: claims.subject_id,
                        role: claims.role,
                        occurred_at_unix_ms: now_unix_ms,
                        outcome: OperatorAuditOutcome::RepositoryDenied,
                    })
                    .map_err(|_| OperatorServiceError::AuditUnavailable)?;
                return Err(OperatorServiceError::RepositoryUnavailable);
            }
        };
        if downgrade_stale_model_evidence {
            downgrade_stale_model_inventory_evidence_to_unknown(&mut overview, now_unix_ms);
        }
        let outcome = if overview.tenant_id != claims.tenant_id
            || validate_overview(&overview, now_unix_ms).is_err()
            || overview
                .to_json()
                .starts_with("{\"error\":\"overview_exceeds_response_budget\"}")
        {
            OperatorAuditOutcome::InvalidOverview
        } else {
            OperatorAuditOutcome::ReadSucceeded
        };
        self.audit
            .append(&OperatorAuditEvent {
                tenant_id: claims.tenant_id.clone(),
                subject_id: claims.subject_id,
                role: claims.role,
                occurred_at_unix_ms: now_unix_ms,
                outcome,
            })
            .map_err(|_| OperatorServiceError::AuditUnavailable)?;
        match outcome {
            OperatorAuditOutcome::ReadSucceeded => Ok(overview),
            OperatorAuditOutcome::InvalidOverview if overview.tenant_id != claims.tenant_id => {
                Err(OperatorServiceError::InvalidTenantBoundary)
            }
            OperatorAuditOutcome::InvalidOverview => Err(OperatorServiceError::InvalidOverview),
            OperatorAuditOutcome::RepositoryDenied => {
                Err(OperatorServiceError::RepositoryUnavailable)
            }
        }
    }

    /// Match an installed model using the authenticated tenant's validated device
    /// inventory. The overview read is audited before matching. This operation is
    /// advisory only: it does not admit a workload, reserve resources, install a model,
    /// start a runtime or dispatch work. Catalogue labels are never used as evidence.
    pub fn match_model_for_task(
        &self,
        session_token: &str,
        device_id: &str,
        model_ref: &str,
        requirements: &ModelTaskRequirements,
        now_unix_ms: u64,
    ) -> Result<OperatorModelTaskMatch, OperatorServiceError> {
        if !valid_identifier(device_id, 128)
            || !valid_bounded_text(model_ref, 160)
            || contains_local_path(model_ref)
        {
            return Err(OperatorServiceError::InvalidModelMatchRequest);
        }

        let overview = self.get_overview_for_model_match(session_token, now_unix_ms)?;
        let device = overview
            .devices
            .iter()
            .find(|device| device.device_id == device_id)
            .ok_or(OperatorServiceError::ModelInventoryUnavailable)?;
        // Model planning is limited to devices whose current operator view proves
        // enrollment, dual-consent-derived schedulability and a fresh last-seen time.
        // A stale inventory row cannot keep a revoked, paused or offline device eligible.
        if device.trust_state != "enrolled"
            || device.availability != "schedulable"
            || device.last_seen_unix_ms == 0
            || device.last_seen_unix_ms > now_unix_ms.saturating_add(CLOCK_SKEW_TOLERANCE_MS)
            || now_unix_ms.saturating_sub(device.last_seen_unix_ms) > MAX_OVERVIEW_AGE_MS
        {
            return Err(OperatorServiceError::ModelInventoryUnavailable);
        }
        let inventory_view = overview
            .model_inventory
            .iter()
            .find(|inventory| inventory.device_id == device_id)
            .ok_or(OperatorServiceError::ModelInventoryUnavailable)?;
        let mut inventory = model_inventory_for_matching(inventory_view)
            .map_err(|_| OperatorServiceError::InvalidOverview)?;
        // The inventory is an OS/runtime free-memory snapshot; the operator view is
        // the current remaining fleet budget after reservations. A fit must satisfy
        // both. If one source is unknown, retain a known insufficiency but never
        // promote a known-sufficient value into a compatibility claim.
        if let Some(required_memory) = requirements.minimum_memory_mb {
            inventory.hardware.memory_available_mb = match (
                inventory.hardware.memory_available_mb,
                device.remaining_memory_mb,
            ) {
                (Some(snapshot), Some(remaining)) => Some(snapshot.min(remaining)),
                (Some(snapshot), None) if snapshot < required_memory => Some(snapshot),
                (None, Some(remaining)) if remaining < required_memory => Some(remaining),
                _ => None,
            };
        }
        let result = match_model_to_task(
            &inventory,
            model_ref,
            requirements,
            now_unix_ms,
            MAX_OVERVIEW_AGE_MS,
        )
        .map_err(|_| OperatorServiceError::ModelMatchRejected)?;

        Ok(OperatorModelTaskMatch {
            device_id: device_id.to_owned(),
            result,
        })
    }

    /// Convenience entry point for the future bounded HTTP request decoder.
    /// Tenant identity is never accepted from the request body.
    pub fn match_model_task_request(
        &self,
        session_token: &str,
        request: &OperatorModelTaskMatchRequest,
        now_unix_ms: u64,
    ) -> Result<OperatorModelTaskMatch, OperatorServiceError> {
        self.match_model_for_task(
            session_token,
            &request.device_id,
            &request.model_ref,
            &request.requirements,
            now_unix_ms,
        )
    }
}

fn model_inventory_for_matching(
    view: &OperatorModelInventoryView,
) -> Result<ModelRuntimeInventory, ModelInventoryValidationError> {
    fn evidence(
        value: &OperatorInventoryEvidence,
    ) -> Result<ModelEvidence, ModelInventoryValidationError> {
        let source = match value.source.as_str() {
            "runtime_api" => EvidenceSource::RuntimeApi,
            "os_api" => EvidenceSource::OsApi,
            "runtime_metadata" => EvidenceSource::RuntimeMetadata,
            "signed_catalogue" => EvidenceSource::SignedCatalogue,
            "published_catalogue" => EvidenceSource::PublishedCatalogue,
            "estimate" => EvidenceSource::Estimate,
            "unknown" => EvidenceSource::Unknown,
            _ => return Err(ModelInventoryValidationError::InvalidEvidence),
        };
        let confidence = match value.confidence.as_str() {
            "verified" => EvidenceConfidence::Verified,
            "reported" => EvidenceConfidence::Reported,
            "estimated" => EvidenceConfidence::Estimated,
            "unknown" => EvidenceConfidence::Unknown,
            _ => return Err(ModelInventoryValidationError::InvalidEvidence),
        };
        Ok(ModelEvidence {
            source,
            confidence,
            observed_at_unix_ms: value.observed_at_unix_ms,
        })
    }

    let hardware = ModelHardware {
        cpu_logical_cores: view
            .hardware
            .cpu_logical_cores
            .map(u16::try_from)
            .transpose()
            .map_err(|_| ModelInventoryValidationError::InvalidHardware)?,
        memory_total_mb: view.hardware.memory_total_mb,
        memory_available_mb: view.hardware.memory_available_mb,
        storage_free_mb: view.hardware.storage_free_mb,
        accelerators: view
            .hardware
            .accelerators
            .iter()
            .map(|item| {
                Ok(AcceleratorInfo {
                    kind: match item.kind.as_str() {
                        "gpu" => AcceleratorKind::Gpu,
                        "npu" => AcceleratorKind::Npu,
                        "other" => AcceleratorKind::Other,
                        _ => return Err(ModelInventoryValidationError::InvalidMetadata),
                    },
                    vendor: item.vendor.clone(),
                    device_family: item.device_family.clone(),
                    memory_mb: item.memory_mb,
                    runtime_api: item.runtime_api.clone(),
                    evidence: evidence(&item.evidence)?,
                })
            })
            .collect::<Result<Vec<_>, ModelInventoryValidationError>>()?,
    };
    let runtimes = view
        .runtimes
        .iter()
        .map(|item| {
            Ok(RuntimeInfo {
                runtime_id: item.runtime_id.clone(),
                provider: item.provider.clone(),
                version: item.version.clone(),
                availability: match item.availability.as_str() {
                    "available" => RuntimeAvailability::Available,
                    "unavailable" => RuntimeAvailability::Unavailable,
                    "unknown" => RuntimeAvailability::Unknown,
                    _ => return Err(ModelInventoryValidationError::InvalidMetadata),
                },
                network_scope: match item.network_scope.as_str() {
                    "loopback_only" => RuntimeNetworkScope::LoopbackOnly,
                    "local_socket" => RuntimeNetworkScope::LocalSocket,
                    "enterprise_internal" => RuntimeNetworkScope::EnterpriseInternal,
                    "not_applicable" => RuntimeNetworkScope::NotApplicable,
                    "unknown" => RuntimeNetworkScope::Unknown,
                    _ => return Err(ModelInventoryValidationError::InvalidMetadata),
                },
                evidence: evidence(&item.evidence)?,
            })
        })
        .collect::<Result<Vec<_>, ModelInventoryValidationError>>()?;
    let models = view
        .models
        .iter()
        .map(|item| {
            let capabilities = item
                .capabilities
                .iter()
                .map(|capability| match capability.as_str() {
                    "chat" => Ok(ModelCapability::Chat),
                    "reasoning" => Ok(ModelCapability::Reasoning),
                    "coding" => Ok(ModelCapability::Coding),
                    "vision" => Ok(ModelCapability::Vision),
                    "embeddings" => Ok(ModelCapability::Embeddings),
                    "tool_use" => Ok(ModelCapability::ToolUse),
                    "streaming" => Ok(ModelCapability::Streaming),
                    "audio_input" => Ok(ModelCapability::AudioInput),
                    "audio_output" => Ok(ModelCapability::AudioOutput),
                    "unknown" => Ok(ModelCapability::Unknown),
                    _ => Err(ModelInventoryValidationError::InvalidMetadata),
                })
                .collect::<Result<Vec<_>, _>>()?;
            Ok(ModelInfo {
                model_ref: item.model_ref.clone(),
                runtime_id: item.runtime_id.clone(),
                display_name: item.display_name.clone(),
                family: item.family.clone(),
                version: item.version.clone(),
                availability: match item.availability.as_str() {
                    "installed" => ModelAvailability::Installed,
                    "downloadable" => ModelAvailability::Downloadable,
                    "unavailable" => ModelAvailability::Unavailable,
                    "unknown" => ModelAvailability::Unknown,
                    _ => return Err(ModelInventoryValidationError::InvalidMetadata),
                },
                size_bytes: item.size_bytes,
                context_length_tokens: item.context_length_tokens,
                estimated_min_memory_mb: item.estimated_min_memory_mb,
                capabilities,
                evidence: evidence(&item.evidence)?,
            })
        })
        .collect::<Result<Vec<_>, ModelInventoryValidationError>>()?;

    Ok(ModelRuntimeInventory {
        schema_version: u16::from(view.schema_version),
        generated_at_unix_ms: view.generated_at_unix_ms,
        device_ref: Some(view.device_id.clone()),
        platform: ModelPlatform {
            os: view.platform.os.clone(),
            os_version: view.platform.os_version.clone(),
            architecture: view.platform.architecture.clone(),
        },
        hardware,
        runtimes,
        models,
        privacy: view.privacy.as_ref().map(|privacy| PrivacyDeclaration {
            contains_prompts: Some(privacy.contains_prompts),
            contains_user_files: Some(privacy.contains_user_files),
            contains_local_paths: Some(privacy.contains_local_paths),
            contains_credentials: Some(privacy.contains_credentials),
        }),
    })
}

fn downgrade_stale_model_inventory_evidence_to_unknown(overview: &mut OperatorOverview, now: u64) {
    fn downgrade(evidence: &mut OperatorInventoryEvidence, inventory_generated_at: u64, now: u64) {
        let valid_source = [
            "runtime_api",
            "os_api",
            "runtime_metadata",
            "signed_catalogue",
            "published_catalogue",
            "estimate",
            "unknown",
        ]
        .contains(&evidence.source.as_str());
        let valid_confidence = ["verified", "reported", "estimated", "unknown"]
            .contains(&evidence.confidence.as_str());
        if !valid_source
            || !valid_confidence
            || (evidence.source == "unknown" && evidence.confidence == "verified")
        {
            return;
        }
        let Some(observed_at) = evidence.observed_at_unix_ms else {
            return;
        };
        // Do not hide zero, future, or post-snapshot timestamps: those remain invalid.
        if observed_at == 0
            || observed_at > now.saturating_add(CLOCK_SKEW_TOLERANCE_MS)
            || observed_at > inventory_generated_at.saturating_add(CLOCK_SKEW_TOLERANCE_MS)
            || now.saturating_sub(observed_at) <= MAX_OVERVIEW_AGE_MS
        {
            return;
        }
        evidence.source = "unknown".into();
        evidence.confidence = "unknown".into();
        evidence.observed_at_unix_ms = None;
    }

    for inventory in &mut overview.model_inventory {
        for accelerator in &mut inventory.hardware.accelerators {
            downgrade(
                &mut accelerator.evidence,
                inventory.generated_at_unix_ms,
                now,
            );
        }
        for runtime in &mut inventory.runtimes {
            downgrade(&mut runtime.evidence, inventory.generated_at_unix_ms, now);
        }
        for model in &mut inventory.models {
            downgrade(&mut model.evidence, inventory.generated_at_unix_ms, now);
        }
    }
}

fn validate_overview(overview: &OperatorOverview, now: u64) -> Result<(), ()> {
    let total_model_rows = overview
        .model_inventory
        .iter()
        .try_fold(0usize, |total, inventory| {
            total.checked_add(inventory.models.len())
        });
    if overview.schema_version != 1
        || !valid_identifier(&overview.tenant_id, 128)
        || overview.generated_at_unix_ms == 0
        || overview.generated_at_unix_ms > now.saturating_add(CLOCK_SKEW_TOLERANCE_MS)
        || now.saturating_sub(overview.generated_at_unix_ms) > MAX_OVERVIEW_AGE_MS
        || overview.devices.len() > MAX_DEVICES
        || overview.workloads.len() > MAX_WORKLOADS
        || overview.approvals.len() > MAX_APPROVALS
        || overview.model_inventory.len() > MAX_DEVICES
        || total_model_rows.is_none_or(|count| count > MAX_TOTAL_MODEL_ROWS)
    {
        return Err(());
    }
    let fleet = &overview.fleet;
    if fleet.registered_devices != overview.devices.len()
        || fleet.trusted_consented_devices > fleet.registered_devices
        || fleet.online_fresh_devices > fleet.trusted_consented_devices
        || fleet.schedulable_devices > fleet.online_fresh_devices
    {
        return Err(());
    }
    let mut ids = HashSet::with_capacity(overview.devices.len());
    for device in &overview.devices {
        if !valid_identifier(&device.device_id, 128)
            || device.display_name.len() > 256
            || device.platform.is_empty()
            || device.platform.len() > 64
            || device.trust_state.is_empty()
            || device.trust_state.len() > 64
            || device.availability.is_empty()
            || device.availability.len() > 64
            || !ids.insert(device.device_id.as_str())
            || device.remaining_cpu_millis == Some(0)
            || device.remaining_memory_mb == Some(0)
        {
            return Err(());
        }
    }

    let mut inventory_devices = HashSet::with_capacity(overview.model_inventory.len());
    for inventory in &overview.model_inventory {
        if !valid_identifier(&inventory.device_id, 128)
            || !ids.contains(inventory.device_id.as_str())
            || !inventory_devices.insert(inventory.device_id.as_str())
            || inventory.schema_version != 1
            || inventory.generated_at_unix_ms == 0
            || !valid_bounded_text(&inventory.platform.os, 32)
            || inventory
                .platform
                .os_version
                .as_ref()
                .is_some_and(|value| !valid_bounded_text(value, 64))
            || !valid_bounded_text(&inventory.platform.architecture, 32)
            || inventory
                .hardware
                .cpu_logical_cores
                .is_some_and(|value| value == 0 || value > 65_535)
            || inventory
                .hardware
                .memory_total_mb
                .is_some_and(|value| value == 0 || value > 16_777_216)
            || inventory
                .hardware
                .memory_total_mb
                .zip(inventory.hardware.memory_available_mb)
                .is_some_and(|(total, available)| available > total)
            || inventory.hardware.accelerators.len() > 32
            || inventory.privacy.as_ref().is_some_and(|privacy| {
                privacy.contains_prompts
                    || privacy.contains_user_files
                    || privacy.contains_local_paths
                    || privacy.contains_credentials
            })
            || inventory.generated_at_unix_ms > now.saturating_add(CLOCK_SKEW_TOLERANCE_MS)
            || now.saturating_sub(inventory.generated_at_unix_ms) > MAX_OVERVIEW_AGE_MS
            || inventory
                .hardware
                .memory_available_mb
                .is_some_and(|value| value > 16_777_216)
            || inventory.runtimes.len() > 16
            || inventory.models.len() > 512
        {
            return Err(());
        }
        for accelerator in &inventory.hardware.accelerators {
            if !["gpu", "npu", "other"].contains(&accelerator.kind.as_str())
                || accelerator
                    .vendor
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 64))
                || accelerator
                    .device_family
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 96))
                || accelerator
                    .runtime_api
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 64))
                || !valid_inventory_evidence(
                    &accelerator.evidence,
                    inventory.generated_at_unix_ms,
                    now,
                )
            {
                return Err(());
            }
        }
        let mut runtime_ids = HashSet::with_capacity(inventory.runtimes.len());
        for runtime in &inventory.runtimes {
            if !valid_identifier(&runtime.runtime_id, 96)
                || !valid_bounded_text(&runtime.provider, 64)
                || runtime
                    .version
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 64))
                || !["available", "unavailable", "unknown"].contains(&runtime.availability.as_str())
                || ![
                    "loopback_only",
                    "local_socket",
                    "enterprise_internal",
                    "not_applicable",
                    "unknown",
                ]
                .contains(&runtime.network_scope.as_str())
                || !runtime_ids.insert(runtime.runtime_id.as_str())
                || !valid_inventory_evidence(&runtime.evidence, inventory.generated_at_unix_ms, now)
            {
                return Err(());
            }
        }
        let mut model_ids = HashSet::with_capacity(inventory.models.len());
        for model in &inventory.models {
            if !valid_bounded_text(&model.model_ref, 160)
                || contains_local_path(&model.model_ref)
                || !valid_identifier(&model.runtime_id, 96)
                || !valid_bounded_text(&model.display_name, 160)
                || contains_local_path(&model.display_name)
                || model
                    .family
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 96))
                || model
                    .version
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 64))
                || !["installed", "downloadable", "unavailable", "unknown"]
                    .contains(&model.availability.as_str())
                || model.context_length_tokens == Some(0)
                || model
                    .estimated_min_memory_mb
                    .is_some_and(|value| value == 0 || value > MAX_MODEL_MEMORY_ESTIMATE_MB)
                || model.capabilities.len() > 16
                || model.capabilities.iter().collect::<HashSet<_>>().len()
                    != model.capabilities.len()
                || model.capabilities.iter().any(|value| {
                    ![
                        "chat",
                        "reasoning",
                        "coding",
                        "vision",
                        "embeddings",
                        "tool_use",
                        "streaming",
                        "audio_input",
                        "audio_output",
                        "unknown",
                    ]
                    .contains(&value.as_str())
                })
                || !model_ids.insert(model.model_ref.as_str())
                || !runtime_ids.contains(model.runtime_id.as_str())
                || !valid_inventory_evidence(&model.evidence, inventory.generated_at_unix_ms, now)
            {
                return Err(());
            }
        }
    }

    if let Some(inventory) = &overview.security_provider_inventory {
        if inventory.schema_version != 1
            || inventory.generated_at_unix_ms == 0
            || inventory.generated_at_unix_ms > now.saturating_add(CLOCK_SKEW_TOLERANCE_MS)
            || inventory.generated_at_unix_ms
                > overview
                    .generated_at_unix_ms
                    .saturating_add(CLOCK_SKEW_TOLERANCE_MS)
            || now.saturating_sub(inventory.generated_at_unix_ms) > MAX_OVERVIEW_AGE_MS
            || inventory.providers.len() > 10_000
        {
            return Err(());
        }
        let mut provider_keys = HashSet::with_capacity(inventory.providers.len());
        for provider in &inventory.providers {
            let category_valid = [
                "malware_protection",
                "firewall",
                "endpoint_detection_response",
                "quarantine",
                "device_isolation",
                "security_updates",
            ]
            .contains(&provider.category.as_str());
            let status_valid = [
                "healthy",
                "attention",
                "alert",
                "not_monitored",
                "unavailable",
                "unknown",
            ]
            .contains(&provider.status.as_str());
            let freshness_valid =
                ["fresh", "stale", "unknown"].contains(&provider.evidence_freshness.as_str());
            let update_valid = ["current", "out_of_date", "unverified", "not_reported"]
                .contains(&provider.update_posture.as_str());
            let identity_valid = valid_identifier(&provider.device_id, 128)
                && ids.contains(provider.device_id.as_str())
                && valid_identifier(&provider.provider_id, 96);
            let evidence_age_policy_valid = provider.evidence_max_age_ms > 0
                && provider.evidence_max_age_ms <= MAX_SECURITY_EVIDENCE_AGE_MS;
            let observed_valid = evidence_age_policy_valid
                && provider.observed_at_unix_ms > 0
                && provider.observed_at_unix_ms <= now.saturating_add(CLOCK_SKEW_TOLERANCE_MS)
                && provider.observed_at_unix_ms
                    <= inventory
                        .generated_at_unix_ms
                        .saturating_add(CLOCK_SKEW_TOLERANCE_MS)
                && match provider.evidence_freshness.as_str() {
                    "fresh" => {
                        now.saturating_sub(provider.observed_at_unix_ms)
                            <= provider.evidence_max_age_ms
                    }
                    "stale" => {
                        now.saturating_sub(provider.observed_at_unix_ms)
                            > provider.evidence_max_age_ms
                    }
                    _ => true,
                };
            let update_checked_valid = provider.update_checked_at_unix_ms.is_none_or(|checked| {
                checked > 0
                    && checked <= now.saturating_add(CLOCK_SKEW_TOLERANCE_MS)
                    && checked
                        <= inventory
                            .generated_at_unix_ms
                            .saturating_add(CLOCK_SKEW_TOLERANCE_MS)
                    && checked
                        <= provider
                            .observed_at_unix_ms
                            .saturating_add(CLOCK_SKEW_TOLERANCE_MS)
                    && now.saturating_sub(checked) <= provider.evidence_max_age_ms
            }) && (provider.update_posture != "current"
                || provider.update_checked_at_unix_ms.is_some())
                && (provider.evidence_freshness == "fresh"
                    || !["current", "out_of_date"].contains(&provider.update_posture.as_str()))
                && (provider.update_posture != "not_reported"
                    || provider.update_checked_at_unix_ms.is_none());
            let capabilities_valid = provider.capabilities.len() <= 32
                && provider
                    .capabilities
                    .iter()
                    .all(|value| valid_identifier(value, 96))
                && provider.capabilities.iter().collect::<HashSet<_>>().len()
                    == provider.capabilities.len();
            let key = format!(
                "{}:{}:{}",
                provider.device_id, provider.provider_id, provider.category
            );
            if !identity_valid
                || !category_valid
                || !status_valid
                || !freshness_valid
                || !evidence_age_policy_valid
                || !update_valid
                || !valid_bounded_text(&provider.evidence_source, 128)
                || !observed_valid
                || !capabilities_valid
                || !update_checked_valid
                || !valid_bounded_text(&provider.update_recommendation, 512)
                || provider
                    .display_name
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 160))
                || provider
                    .update_channel
                    .as_ref()
                    .is_some_and(|value| !valid_bounded_text(value, 160))
                || !provider_keys.insert(key)
            {
                return Err(());
            }
        }
    }

    for workload in &overview.workloads {
        if !valid_identifier(&workload.workload_id, 128)
            || workload.title.len() > 256
            || workload.state.len() > 64
            || workload.class.len() > 64
            || workload.reason.as_ref().is_some_and(|v| v.len() > 512)
        {
            return Err(());
        }
    }
    for approval in &overview.approvals {
        if !valid_identifier(&approval.approval_id, 128)
            || approval.title.len() > 256
            || approval.state.len() > 64
            || approval.requester.len() > 128
            || approval.scope.len() > 256
            || approval.expires_at.as_ref().is_some_and(|v| v.len() > 64)
        {
            return Err(());
        }
    }
    Ok(())
}

